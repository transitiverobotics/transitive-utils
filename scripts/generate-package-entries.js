const fs = require('node:fs');
const path = require('node:path');

const packageRoot = path.resolve(__dirname, '..');
const exportsObject = require(packageRoot);
const exportNames = Object.keys(exportsObject).sort();

const declarationSources = [
  {
    name: 'CommonType',
    path: './common/common',
  },
  {
    name: 'DataCacheType',
    path: './common/datacache/DataCache',
  },
  {
    name: 'MqttSyncType',
    path: './common/MqttSync',
  },
  {
    name: 'CloudType',
    path: './server/cloud',
  },
  {
    name: 'ServerType',
    path: './server/server',
  }
];

const esmLines = [
  '// Generated by scripts/generate-package-entries.js.',
  "import utils from './index.js';",
  '',
  ...exportNames.flatMap((name, index) => [
    `const __export${index} = utils[${JSON.stringify(name)}];`,
    `export { __export${index} as ${name} };`
  ]),
  '',
  'export default utils;',
  ''
];

const declarationLines = [
  '// Generated by scripts/generate-package-entries.js.',
  ...declarationSources.map(source =>
    `import * as ${source.name} from '${source.path}';`),
  '',
  ...declarationSources.map(source => `export * from '${source.path}';`),
  '',
  '',
  `declare const utils: ${
  declarationSources.map(source => `typeof ${source.name}`).join('\n  & ')
  };`,
  '',
  'export default utils;',
  ''
];

fs.writeFileSync(path.join(packageRoot, 'index.mjs'), esmLines.join('\n'));
fs.writeFileSync(path.join(packageRoot, 'index.d.ts'), declarationLines.join('\n'));
